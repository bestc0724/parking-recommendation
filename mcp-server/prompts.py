"""
MCP Prompts — 预定义的提示模板
"""


def find_parking_prompt() -> str:
    """引导用户描述停车需求"""
    return (
        "请描述您的停车需求，我可以帮您找到最合适的车位。\n\n"
        "您可以告诉我：\n"
        "- 车辆限高要求（如：我的车2.3米高）\n"
        "- 是否需要充电桩（如：我是新能源车，需要充电）\n"
        "- 价格偏好（如：越便宜越好）\n"
        "- 距离偏好（如：离电梯近一点）\n\n"
        "直接用自然语言描述即可，我会帮您智能匹配。"
    )


def check_reservations_prompt(user_id: str) -> str:
    """查询用户的预约状态"""
    return f"请帮我查询用户 {user_id} 的所有预约记录，包括预约状态和过期时间。"
